import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { AgentRunner } from "./adapters.js";
import { fill, prompt, schema } from "./assets.js";
import { run } from "./exec.js";
import type { Config } from "./config.js";
import { constraintsBlock, loadConstraints, vetoViolations } from "./constraints.js";
import { plannerRoute, researcherRoute } from "./routing.js";
import type { Tier } from "./types.js";
import type { Work } from "./work.js";

export interface ResearchOutput {
  answers: { question: string; answer: string; confidence: "high" | "medium" | "low"; evidence: { source: string; level: number; ref: string }[] }[];
  /** Earlier decisions on the same topic, found in the decision paths and git history. Empty is allowed only with a `decision_check`. */
  prior_decisions: { decision: string; date: string; source: string; contradicts_request: boolean }[];
  /** What was searched for earlier decisions (paths, commands) and what came back, including "nothing found". */
  decision_check: string;
  unverified: string[];
  outcome: "done" | "needs_poc" | "blocked";
  open_question: string;
}

export interface PlanOutput {
  direction: string;
  why: string;
  /** Rigor class: A = money, canonical writes, migrations, irreversible; B = internal logic; C = UI and docs. */
  risk: "A" | "B" | "C";
  /** Class A: how it can fail, what it does, how it is detected, how it is undone. */
  failure_modes: { mode: string; effect: string; detection: string; undo: string }[];
  /** Where and with which command each claim of "works" was or will be proven. */
  verification: { claim: string; where: string; command: string }[];
  /** Options a human vetoed that applied to this work, and why each is out. */
  eliminated_options: { option: string; reason: string }[];
  alternatives: { option: string; why_rejected: string }[];
  steps: { action: string; files: string[] }[];
  exit_criteria: string[];
  risks: { risk: string; containment: string }[];
  outcome: "done" | "needs_poc" | "blocked";
  open_question: string;
}

const outcomeLine = (o: { outcome: string; open_question: string }) =>
  `**Outcome:** \`${o.outcome}\`${o.outcome !== "done" && o.open_question ? ` — ${o.open_question}` : ""}`;

export function renderResearch(r: ResearchOutput, at: string): string {
  const out = [`# Research`, "", `Generated by rafoflow on ${at}.`, "", outcomeLine(r), ""];
  r.answers.forEach((a, i) => {
    out.push(`## ${i + 1}. ${a.question}`, "", a.answer, "", `Confidence: ${a.confidence}.`, "");
    if (a.evidence.length) {
      out.push("| Source | Level | Reference |", "| --- | --- | --- |");
      a.evidence.forEach((e) => out.push(`| ${e.source.replaceAll("|", "\\|")} | ${e.level} | ${e.ref.replaceAll("|", "\\|")} |`));
      out.push("");
    }
  });
  out.push("## Prior decisions", "", `Checked: ${r.decision_check}`, "");
  if (r.prior_decisions?.length) out.push(...r.prior_decisions.map((d) => `- ${d.contradicts_request ? "**ALREADY DECIDED** " : ""}${d.decision} (${d.date}; ${d.source})`), "");
  out.push("## Not verified", "", ...(r.unverified.length ? r.unverified.map((u) => `- ${u}`) : ["- Nothing reported."]), "");
  return out.join("\n");
}

export function renderPlan(p: PlanOutput, at: string): string {
  const out = [`# Plan`, "", `Generated by rafoflow on ${at}. Needs explicit human approval: \`rafoflow approve plan\`.`, "", outcomeLine(p), ""];
  out.push("## Direction", "", p.direction, "", p.why, "");
  out.push(`**Risk class:** ${p.risk ?? "unset"}`, "");
  out.push("## Eliminated options (vetoed by the owner)", "", ...(p.eliminated_options?.length ? p.eliminated_options.map((e) => `- **${e.option}** — ${e.reason}`) : ["- None applied."]), "");
  out.push("## Alternatives rejected", "", ...(p.alternatives.length ? p.alternatives.map((a) => `- **${a.option}** — ${a.why_rejected}`) : ["- None considered."]), "");
  out.push("## Steps", "", ...p.steps.map((s, i) => `${i + 1}. ${s.action}${s.files.length ? ` (${s.files.map((f) => `\`${f}\``).join(", ")})` : ""}`), "");
  out.push("## Exit criteria", "", ...p.exit_criteria.map((c) => `- ${c}`), "");
  if (p.failure_modes?.length) out.push("## Failure modes", "", "| Mode | Effect | Detected by | Undo |", "| --- | --- | --- | --- |", ...p.failure_modes.map((f) => `| ${[f.mode, f.effect, f.detection, f.undo].map((c) => c.replaceAll("|", "\\|")).join(" | ")} |`), "");
  if (p.verification?.length) out.push("## Verification matrix", "", "| Claim | Where | Command |", "| --- | --- | --- |", ...p.verification.map((v) => `| ${[v.claim, v.where, `\`${v.command}\``].map((c) => c.replaceAll("|", "\\|")).join(" | ")} |`), "");
  out.push("## Risks", "", ...(p.risks.length ? p.risks.map((r) => `- **${r.risk}** — ${r.containment}`) : ["- None identified."]), "");
  return out.join("\n");
}

interface RoleDeps {
  config: Config;
  tier: Tier;
  cwd: string;
  work: Work;
  runner: AgentRunner;
}

/** Earlier decisions the researcher must check before recommending: the decision paths and their recent git history. */
export function decisionsContext(cwd: string, paths: string[]): string {
  if (paths.length === 0) return "No decision paths are configured (`docs.decisions`). Search the changelog and the git log yourself.";
  const log = run("git", ["log", "--oneline", "-n", "50", "--", ...paths], { cwd });
  return `Decision paths: ${paths.join(", ")}\n\nRecent history of those paths (git log --oneline -n 50):\n${log.code === 0 && log.out.trim() ? log.out.trim() : "(no history)"}`;
}

export function research(d: RoleDeps & { request: string; questions: string[] }): ResearchOutput {
  const route = researcherRoute(d.config, d.tier);
  const res = d.runner({
    label: "researcher",
    prompt: fill(prompt("researcher"), { request: d.request || "(not given)", questions: d.questions.map((q, i) => `${i + 1}. ${q}`).join("\n"), constraints: constraintsBlock(loadConstraints(d.cwd)), decisions: decisionsContext(d.cwd, d.config.docs.decisions) }),
    cwd: d.cwd,
    access: "research",
    route,
    schema: schema("research"),
  });
  d.work.saveRaw(`research-${res.harness}.txt`, res.raw);
  const out = res.json as ResearchOutput | undefined;
  if (!out?.answers) throw new Error(`researcher returned no valid result: ${res.text.slice(0, 300)}`);
  // "Nothing found" is an answer only when it says what was searched.
  if (!out.decision_check?.trim()) throw new Error("researcher did not report its decision check: say what was searched for earlier decisions, even when nothing was found");
  const at = new Date().toISOString();
  writeFileSync(join(d.work.dir, "research.md"), renderResearch(out, at));
  writeFileSync(join(d.work.dir, "research.json"), JSON.stringify(out, null, 2) + "\n");
  d.work.log({ step: "research", harness: res.harness, model: res.model, ms: res.ms, cost_usd: res.cost_usd, outcome: out.outcome, questions: d.questions.length, unverified: out.unverified.length });
  return out;
}

export function plan(d: RoleDeps & { request: string }): PlanOutput {
  const route = plannerRoute(d.config, d.tier);
  const researchPath = join(d.work.dir, "research.md");
  const res = d.runner({
    label: "planner",
    prompt: fill(prompt("planner"), { request: d.request || "(not given)", tier: d.tier, research: existsSync(researchPath) ? readFileSync(researchPath, "utf8") : "(none)", constraints: constraintsBlock(loadConstraints(d.cwd)) }),
    cwd: d.cwd,
    access: "read",
    route,
    schema: schema("plan"),
  });
  d.work.saveRaw(`plan-${res.harness}.txt`, res.raw);
  const out = res.json as PlanOutput | undefined;
  if (!out?.direction) throw new Error(`planner returned no valid plan: ${res.text.slice(0, 300)}`);
  // A plan that uses a vetoed option is not shown as `done`: the typed outcome says a human has to look.
  const violated = vetoViolations(out, loadConstraints(d.cwd));
  if (violated.length > 0) {
    out.outcome = "blocked";
    out.open_question = `The plan uses an option the owner vetoed: ${violated.map((v) => v.text).join("; ")}. Decide whether the veto still stands.`;
    d.work.log({ step: "veto_violation", constraints: violated.map((v) => v.id) });
  }
  const at = new Date().toISOString();
  writeFileSync(join(d.work.dir, "plan.md"), renderPlan(out, at));
  writeFileSync(join(d.work.dir, "plan.json"), JSON.stringify(out, null, 2) + "\n");
  d.work.log({ step: "plan", harness: res.harness, model: res.model, ms: res.ms, cost_usd: res.cost_usd, outcome: out.outcome, steps: out.steps.length });
  return out;
}
